    # Северная граница (от запада к востоку)
    [33.42, 51.62], [33.50, 51.64], [33.60, 51.66], [33.72, 51.67], [33.85, 51.68],
    [34.00, 51.69], [34.15, 51.70], [34.30, 51.71], [34.45, 51.72], [34.60, 51.72],
