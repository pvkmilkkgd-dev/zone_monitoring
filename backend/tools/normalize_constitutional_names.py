def normalize_to_constitutional(name: str) -> str:
    """Приводит название к конституционному."""
    if not name:
        return name
    
    name = name.strip()
    
    # Проверяем точное совпадение
    if name in CONSTITUTIONAL_NAMES:
        return CONSTITUTIONAL_NAMES[name]
    
    # Пробуем найти частичное совпадение
    for key, value in CONSTITUTIONAL_NAMES.items():
        # Убираем возможные различия в пробелах и тире для сравнения
        normalized_key = key.replace(" ", "").replace("-", "").replace("—", "")
        normalized_name = name.replace(" ", "").replace("-", "").replace("—", "")
        
        if normalized_key.lower() == normalized_name.lower():
            return value
        
        # Также проверяем, начинается ли ключ с текущего названия
        if normalized_name.lower() in normalized_key.lower() or normalized_key.lower() in normalized_name.lower():
            if len(key) > len(name) and abs(len(key) - len(name)) < 10:
                return value
    
    # Если не найдено, возвращаем исходное название
    return name


def normalize_all_to_constitutional(db: Session):
    """Приводит все названия регионов к конституционным."""
    print("=== Приведение названий регионов к конституционным (Статья 65 Конституции РФ) ===\n")
    
    regions = db.execute(
        text("SELECT id, name, name_original FROM regions ORDER BY name")
    ).all()
    
    updated_name_count = 0
    skipped_count = 0
    
    for region in regions:
        region_id = region.id
        current_name = region.name
        
        if not current_name:
            skipped_count += 1
            continue
        
        # Приводим к конституционному названию
        constitutional_name = normalize_to_constitutional(current_name)
        
        if constitutional_name != current_name:
            try:
                db.execute(
                    text("UPDATE regions SET name = :constitutional_name, updated_at = NOW() WHERE id = :region_id"),
                    {"constitutional_name": constitutional_name, "region_id": region_id}
                )
                print(f"  '{current_name}' -> '{constitutional_name}'")
                updated_name_count += 1
            except Exception as e:
                print(f"Ошибка при обновлении '{current_name}': {e}")
                db.rollback()
                continue
        else:
            skipped_count += 1
    
    db.commit()
    
    print(f"\n=== Результаты ===")
    print(f"Обновлено названий: {updated_name_count}")
    print(f"Оставлено без изменений: {skipped_count}")
    
    total = db.execute(text("SELECT COUNT(*) FROM regions")).scalar()
    print(f"\nВсего регионов в БД: {total}")
    
    # Показываем примеры названий для проверки
    print("\nПримеры названий с тире (проверка формата):")
    dash_names = db.execute(
        text("SELECT name FROM regions WHERE name LIKE '%-%' ORDER BY name LIMIT 10")
    ).scalars().all()
    for n in dash_names:
        print(f"  - {n}")


def main():
    db = SessionLocal()
    try:
        normalize_all_to_constitutional(db)
    except Exception as e:
        db.rollback()
        print(f"\nERROR: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)
    finally:
        db.close()


if __name__ == "__main__":
    main()
